// Word-by-word reveal caption
const Caption: React.FC<{
  text: string;
  start?: number;
  size?: number;
  color?: string;
  weight?: number;
  maxWidth?: number;
  align?: 'left' | 'center';
}> = ({ text, start = 0, size = 32, color = C.text, weight = 500, maxWidth = 1500, align = 'left' }) => {
  const frame = useCurrentFrame();
  const words = text.split(/\s+/);
  return (
    <div
      style={{
        fontSize: size,
        fontWeight: weight,
        color,
        lineHeight: 1.45,
        maxWidth,
        textAlign: align,
        marginLeft: align === 'center' ? 'auto' : 0,
        marginRight: align === 'center' ? 'auto' : 0,
      }}
    >
      {words.map((w, i) => {
        const t = start + i * 2;
        const op = interpolate(frame, [t, t + 8], [0, 1], {
          extrapolateLeft: 'clamp',
          extrapolateRight: 'clamp',
        });
        const ty = interpolate(frame, [t, t + 8], [10, 0], {
          extrapolateLeft: 'clamp',
          extrapolateRight: 'clamp',
        });
        return (
          <span
            key={i}
            style={{
              display: 'inline-block',
              opacity: op,
              transform: `translateY(${ty}px)`,
              marginRight: 10,
            }}
          >
            {w}
          </span>
        );
      })}
    </div>
  );
};

const FadeIn: React.FC<{
  start?: number;
  duration?: number;
  children: React.ReactNode;
  y?: number;
}> = ({ start = 0, duration = 14, children, y = 24 }) => {
  const frame = useCurrentFrame();
  const op = interpolate(frame, [start, start + duration], [0, 1], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });
  const ty = interpolate(frame, [start, start + duration], [y, 0], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });
  return <div style={{ opacity: op, transform: `translateY(${ty}px)` }}>{children}</div>;
};

