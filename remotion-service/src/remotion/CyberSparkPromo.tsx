/**
 * CyberSparkPromo — a ~5 minute promotional video for
 * "India Israel CyberSpark Academy" built with Remotion.
 *
 * The video is self-contained: it animates branded captions, stats and
 * course cards, and overlays the 5 website screenshots from
 *   public/cyberspark/slide1.png ... slide5.png
 *
 * If a slide PNG is missing, a styled placeholder is shown instead so
 * the video still renders cleanly.
 *
 * Total runtime: 300 seconds (5:00) at 30 fps.
 */
import React from 'react';
import {
  AbsoluteFill,
  Audio,
  Img,
  Sequence,
  getStaticFiles,
  interpolate,
  spring,
  staticFile,
  useCurrentFrame,
  useVideoConfig,
} from 'remotion';
import { FONT_STACK } from './fonts';

// Snapshot of available static files at module load time. Used to skip
// missing slide PNGs / scene WAVs without triggering Remotion's
// delayRender timeout (which fires when <Img> can't resolve a URL).
const STATIC_FILES = new Set(getStaticFiles().map((f) => f.name));
const has = (rel: string) => STATIC_FILES.has(rel);

// ---------- Brand palette ------------------------------------------------
const C = {
  navy: '#0b2545',
  navyDeep: '#061427',
  orange: '#e08a1f',
  orangeBright: '#ffb347',
  cream: '#f5f1e8',
  white: '#ffffff',
  text: '#e8edf5',
  muted: '#9fb0c8',
};

// Try to resolve a slide PNG. If it does not exist we fall through to a
// branded placeholder. We can't synchronously check existence in the
// browser, so we just attempt the load and let <Img onError> handle it.
const slide = (n: number) => {
  const rel = `cyberspark/slide${n}.png`;
  return has(rel) ? staticFile(rel) : null;
};

// Resolve a Sarvam-narrated WAV for a scene (generated by
// scripts/narrate_cyberspark.mjs). Returns null if the file isn't on disk
// yet so the video still renders silently.
const audio = (name: string) => {
  const rel = `cyberspark/audio/${name}.wav`;
  return has(rel) ? staticFile(rel) : null;
};

const SceneAudio: React.FC<{ name: string }> = ({ name }) => {
  const src = audio(name);
  if (!src) return null;
  return <Audio src={src} />;
};

