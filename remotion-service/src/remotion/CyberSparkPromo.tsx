// Slide screenshot frame (right side); falls back to placeholder if image missing
const SlideFrame: React.FC<{ src: string | null; label: string; start?: number }> = ({
  src,
  label,
  start = 0,
}) => {
  const frame = useCurrentFrame();
  const { fps } = useVideoConfig();
  const s = spring({ frame: frame - start, fps, config: { damping: 16, mass: 0.6 } });
  const sc = interpolate(s, [0, 1], [0.92, 1]);
  const op = interpolate(s, [0, 1], [0, 1]);
  return (
    <div
      style={{
        transform: `scale(${sc})`,
        opacity: op,
        borderRadius: 16,
        overflow: 'hidden',
        boxShadow: '0 30px 80px rgba(0,0,0,0.55), 0 0 0 1px rgba(255,255,255,0.08)',
        background: C.navy,
        border: `2px solid ${C.orange}55`,
        position: 'relative',
        width: 880,
      }}
    >
      {src ? (
        <Img
          src={src}
          style={{ width: '100%', display: 'block' }}
          onError={(e) => {
            (e.target as HTMLImageElement).style.display = 'none';
          }}
        />
      ) : null}
      {!src ? <Placeholder label={label} /> : null}
      <div
        style={{
          position: 'absolute',
          bottom: 0,
          left: 0,
          right: 0,
          padding: '10px 16px',
          fontSize: 14,
          letterSpacing: 3,
          textTransform: 'uppercase',
          color: C.cream,
          background: `linear-gradient(0deg, ${C.navyDeep}f0, transparent)`,
          fontWeight: 700,
        }}
      >
        {label}
      </div>
    </div>
  );
};

